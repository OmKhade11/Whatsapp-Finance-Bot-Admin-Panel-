-- Run this in Supabase SQL Editor before pointing the API at SUPABASE_DB_URL.
create table if not exists public.income (
    id bigint generated by default as identity primary key,
    user_id text not null,
    amount numeric(18,2) not null check (amount > 0),
    entry_date date not null,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists income_user_date_idx on public.income(user_id, entry_date);

create table if not exists public.expenses (
    id bigint generated by default as identity primary key,
    user_id text not null,
    category varchar(120) not null,
    amount numeric(18,2) not null check (amount > 0),
    entry_date date not null,
    note text,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists expenses_user_date_idx on public.expenses(user_id, entry_date);

create table if not exists public.subscriptions (
    id bigint generated by default as identity primary key,
    user_id text not null unique,
    tier varchar(20) not null default 'FREE' check (tier in ('FREE','PLUS','PREMIUM')),
    active boolean not null default true,
    expires_at timestamptz
);

create table if not exists public.payments (
    id bigint generated by default as identity primary key,
    provider_event_id varchar(255) not null unique,
    user_id text not null,
    tier varchar(20) not null check (tier in ('PLUS','PREMIUM')),
    status varchar(30) not null
);

create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    user_id text not null,
    message text not null,
    read boolean not null default false,
    created_at timestamptz not null default now()
);
create index if not exists notifications_user_idx on public.notifications(user_id, created_at desc);
